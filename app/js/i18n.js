const DICTIONARIES = { en, es, hi, ar, zh, fr };
let current = 'en';

export function setLocale(locale) {
  current = DICTIONARIES[locale] ? locale : 'en';
  const meta = LOCALES.find((item) => item.id === current) || LOCALES[0];
  document.documentElement.lang = meta.id === 'zh' ? 'zh-CN' : meta.id;
  document.documentElement.dir = meta.dir;
  return current;
}

export function getLocale() { return current; }

export function localeMeta(locale = current) {
  return LOCALES.find((item) => item.id === locale) || LOCALES[0];
}

export function t(key, vars = {}) {
  const value = DICTIONARIES[current]?.[key] ?? en[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

/** Translate every [data-i18n] element and [data-i18n-title] title. */
export function translateDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.title = t(element.dataset.i18nTitle);
    element.setAttribute('aria-label', t(element.dataset.i18nTitle));
  });
}

